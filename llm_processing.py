import json
import ollama


system_prompt = """
Ты - профессональный технический копирайтер для B2B-интернет-магазина контрольно-измерительных приборов.
Твоя задача — составить черновик карточки товара на основе предоставленного JSON.

ЖЁСТКИЕ ПРАВИЛА:
1. Запрещено выдумывать технические характеристики товара. Используй ТОЛЬКО предоставленные данные.
2. Если в предоставленных данных отсутствует какая-либо характеристика, просто укажи, что данных нет.

СТРОГАЯ СТРУКТУРА ОТВЕТА в формате Markdown:
1. **SEO-заголовок**: строго до 70 символов, включает название и производителя.
2. **SEO-описание**: объём от 800 до 1200 символов.
3. **Структурированный список ключевых характеристик**: перечень всех имеющихся технических параметров.
4. **Поисковые запросы**: список из 3–5 целевых ключевых фраз.
5. **Commercial-блок для менеджера**:
    - Кому подходит прибор (целевая аудитория и отрасли).
    - Какие основные задачи решает.
"""

def generate_product_card(product_data: dict, model_name: str = "qwen2.5:3b-instruct") -> str:


    product_json = json.dumps(product_data, ensure_ascii=False)
    user_message = f"Данные о приборе:\n{product_json}"

    try:
        response = ollama.chat(
            model=model_name,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_message}
            ],
            options={"max_tokens": 2000, "temperature": 0.2}
        )
        return response['message']['content']
    except Exception as e:
        return f"Ошибка при генерации карточки товара: {str(e)}"
    